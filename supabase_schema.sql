create extension if not exists "pgcrypto";

-- 1. Core interviews table
create table if not exists public.interviews (
  id bigint generated by default as identity primary key,
  title text not null,
  role text,
  user_id uuid references auth.users(id) on delete cascade,
  created_at timestamptz default now()
);

-- Idempotent column additions for existing installations
alter table public.interviews add column if not exists role text;
alter table public.interviews add column if not exists user_id uuid references auth.users(id) on delete cascade;

-- Seed default interview if empty
insert into public.interviews (title, role)
select 'AI Technical Drill', 'Full Stack Engineer'
where not exists (select 1 from public.interviews limit 1);

-- 2. Questions table
create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  interview_id bigint references public.interviews(id) on delete cascade,
  question text not null,
  options jsonb,
  correct_answer text,
  explanation text,
  created_at timestamptz default now()
);

-- 3. Results / Analytics table
create table if not exists public.results (
  id bigint generated by default as identity primary key,
  interview_id bigint references public.interviews(id) on delete cascade,
  score numeric,
  feedback text,
  user_id uuid references auth.users(id) on delete cascade,
  created_at timestamptz default now()
);

-- Idempotent column additions for results
alter table public.results add column if not exists user_id uuid references auth.users(id) on delete cascade;

-- 4. Performance & Relationship Indexes
create index if not exists idx_interviews_created_at on public.interviews(created_at desc);
create index if not exists idx_questions_interview_id on public.questions(interview_id);
create index if not exists idx_results_interview_id on public.results(interview_id);
create index if not exists idx_results_created_at on public.results(created_at desc);

-- 5. Row Level Security (RLS) Configuration
alter table public.interviews enable row level security;
alter table public.questions enable row level security;
alter table public.results enable row level security;

-- Idempotent Policies for interviews
drop policy if exists "Allow read interviews" on public.interviews;
create policy "Allow read interviews" on public.interviews for select using (true);

drop policy if exists "Allow insert interviews" on public.interviews;
create policy "Allow insert interviews" on public.interviews for insert with check (true);

drop policy if exists "Allow update interviews" on public.interviews;
create policy "Allow update interviews" on public.interviews for update using (true);

-- Idempotent Policies for questions
drop policy if exists "Allow read questions" on public.questions;
create policy "Allow read questions" on public.questions for select using (true);

drop policy if exists "Allow insert questions" on public.questions;
create policy "Allow insert questions" on public.questions for insert with check (true);

-- Idempotent Policies for results
drop policy if exists "Allow read results" on public.results;
create policy "Allow read results" on public.results for select using (true);

drop policy if exists "Allow insert results" on public.results;
create policy "Allow insert results" on public.results for insert with check (true);
