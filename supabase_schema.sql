create extension if not exists "pgcrypto";
create extension if not exists "uuid-ossp";

-- ----------------------------------------------------------------------------
-- 1. USERS DIRECTORY
-- ----------------------------------------------------------------------------
create table if not exists public.users (
  id uuid primary key default gen_random_uuid(),
  name text,
  email text unique,
  avatar_url text,
  provider text,
  created_at timestamptz default now()
);

alter table public.users add column if not exists name text;
alter table public.users add column if not exists email text;
alter table public.users add column if not exists avatar_url text;
alter table public.users add column if not exists provider text;
alter table public.users add column if not exists created_at timestamptz default now();

-- ----------------------------------------------------------------------------
-- 2. SCHOLAR PROFILES (User settings, exams, practice stats, and chat history)
-- ----------------------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key,
  selected_exam text,
  exam_history jsonb default '[]'::jsonb,
  completed_topics jsonb default '[]'::jsonb,
  practice_stats jsonb default '{"total": 0, "correct": 0, "sessions": 0}'::jsonb,
  chat_history jsonb default '[]'::jsonb,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

alter table public.profiles add column if not exists selected_exam text;
alter table public.profiles add column if not exists exam_history jsonb default '[]'::jsonb;
alter table public.profiles add column if not exists completed_topics jsonb default '[]'::jsonb;
alter table public.profiles add column if not exists practice_stats jsonb default '{"total": 0, "correct": 0, "sessions": 0}'::jsonb;
alter table public.profiles add column if not exists chat_history jsonb default '[]'::jsonb;
alter table public.profiles add column if not exists created_at timestamptz default now();
alter table public.profiles add column if not exists updated_at timestamptz default now();

-- ----------------------------------------------------------------------------
-- 3. DOCUMENTS & RAG CHUNKS (Notes & Study material)
-- ----------------------------------------------------------------------------
create table if not exists public.documents (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  uploaded_at timestamp without time zone default now(),
  user_id uuid,
  created_at timestamptz default now()
);

alter table public.documents add column if not exists name text;
alter table public.documents add column if not exists uploaded_at timestamp without time zone default now();
alter table public.documents add column if not exists user_id uuid;

create table if not exists public.chunks (
  id uuid primary key default gen_random_uuid(),
  document_id uuid references public.documents(id) on delete cascade,
  document_name text,
  chunk_text text not null,
  created_at timestamp without time zone default now()
);

alter table public.chunks add column if not exists document_id uuid;
alter table public.chunks add column if not exists document_name text;
alter table public.chunks add column if not exists chunk_text text;

-- ----------------------------------------------------------------------------
-- 4. PRACTICE DRILL HISTORY
-- ----------------------------------------------------------------------------
create table if not exists public.practice_history (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null,
  topic text,
  score integer,
  created_at timestamp without time zone default now()
);

alter table public.practice_history add column if not exists topic text;
alter table public.practice_history add column if not exists score integer;
alter table public.practice_history add column if not exists created_at timestamp without time zone default now();

-- ----------------------------------------------------------------------------
-- 5. INTERVIEWS, QUESTIONS & RESULTS (MCQ Exam Engine)
-- ----------------------------------------------------------------------------
create table if not exists public.interviews (
  id bigint generated by default as identity primary key,
  title text not null,
  role text,
  user_id uuid,
  created_at timestamptz default now()
);

alter table public.interviews add column if not exists role text;
alter table public.interviews add column if not exists user_id uuid;

insert into public.interviews (title, role)
select 'AI Technical Drill', 'Full Stack Engineer'
where not exists (select 1 from public.interviews limit 1);

create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  interview_id bigint references public.interviews(id) on delete cascade,
  question text not null,
  options jsonb,
  correct_answer text,
  explanation text,
  created_at timestamptz default now()
);

create table if not exists public.results (
  id bigint generated by default as identity primary key,
  interview_id bigint references public.interviews(id) on delete cascade,
  score numeric,
  feedback text,
  user_id uuid,
  created_at timestamptz default now()
);

-- ----------------------------------------------------------------------------
-- 6. INDEXES
-- ----------------------------------------------------------------------------
create index if not exists idx_profiles_updated_at on public.profiles(updated_at desc);
create index if not exists idx_practice_history_user on public.practice_history(user_id);
create index if not exists idx_practice_history_created on public.practice_history(created_at desc);
create index if not exists idx_documents_user on public.documents(user_id);
create index if not exists idx_chunks_doc on public.chunks(document_id);
create index if not exists idx_interviews_created_at on public.interviews(created_at desc);
create index if not exists idx_questions_interview_id on public.questions(interview_id);
create index if not exists idx_results_interview_id on public.results(interview_id);

-- ----------------------------------------------------------------------------
-- 7. ROLE PERMISSIONS
-- ----------------------------------------------------------------------------
grant usage on schema public to postgres, anon, authenticated, service_role;
grant all on all tables in schema public to postgres, anon, authenticated, service_role;
grant all on all sequences in schema public to postgres, anon, authenticated, service_role;
alter default privileges in schema public grant all on tables to postgres, anon, authenticated, service_role;
alter default privileges in schema public grant all on sequences to postgres, anon, authenticated, service_role;

-- ----------------------------------------------------------------------------
-- 8. SECURITY HARDENING: FUNCTIONS (Fixes search_path & RPC execution)
-- ----------------------------------------------------------------------------
do $$
begin
  if exists (select 1 from pg_proc where proname = 'handle_new_user' and pronamespace = 'public'::regnamespace) then
    execute 'alter function public.handle_new_user() set search_path = public, pg_temp';
    execute 'revoke execute on function public.handle_new_user() from public, anon, authenticated';
    execute 'grant execute on function public.handle_new_user() to postgres, service_role';
  end if;

  if exists (select 1 from pg_proc where proname = 'rls_auto_enable' and pronamespace = 'public'::regnamespace) then
    execute 'alter function public.rls_auto_enable() set search_path = public, pg_temp';
    execute 'revoke execute on function public.rls_auto_enable() from public, anon, authenticated';
    execute 'grant execute on function public.rls_auto_enable() to postgres, service_role';
  end if;
end $$;

